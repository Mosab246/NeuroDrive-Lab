"""The benchmark pipeline end to end at toy scale: train, evaluate, resume, report."""

import json

import pytest

from neurodrive.benchmark.config import load_benchmark_config
from neurodrive.benchmark.report import build_report
from neurodrive.benchmark.runner import Benchmark


@pytest.fixture(scope="module")
def bench(tmp_path_factory):
    cfg = load_benchmark_config("configs/benchmark/smoke.yaml")
    root = tmp_path_factory.mktemp("bench")
    b = Benchmark(cfg, root=root, log=lambda *_: None)
    b.run()
    return b


def test_every_run_trained_and_evaluated(bench):
    runs = bench.manifest["runs"]
    assert set(runs) == {"ppo/0", "neat/0", "ppo/1", "neat/1"}
    assert all(r["status"] == "evaluated" for r in runs.values())
    assert (bench.dir / "eval" / "heuristic" / "episodes.csv").is_file()


def test_rerun_resumes_without_retraining(bench):
    trained = []
    again = Benchmark(bench.config, root=bench.dir.parent, log=trained.append)
    again.run()
    assert not any("training" in str(line) for line in trained)


def test_changing_an_existing_benchmark_is_refused(bench):
    changed = bench.config.model_copy(update={"budget_env_steps": 999})
    with pytest.raises(ValueError, match="different config"):
        Benchmark(changed, root=bench.dir.parent)


def test_report_files(bench, tmp_path):
    out = build_report(bench.dir, tmp_path / "report")
    for name in (
        "report.md",
        "runs.csv",
        "per_track.csv",
        "aggregate.json",
        "learning_curves.png",
        "test_lap_times.png",
    ):
        assert (out / name).is_file(), name
    agg = json.loads((out / "aggregate.json").read_text(encoding="utf-8"))
    assert agg["aggregate"]["ppo"]["seeds"] == [0, 1]
    assert agg["aggregate"]["neat"]["pooled_episodes"] == 8  # 2 seeds x 2 tracks x 2
    text = (out / "report.md").read_text(encoding="utf-8")
    assert "Generated by" in text and "| PPO | 0 |" in text
