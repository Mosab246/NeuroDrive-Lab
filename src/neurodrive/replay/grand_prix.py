"""A Grand Prix: a series of real races, scored like a championship.

Every race uses the same drivers on a different track. The starting grid is rotated each
race (race ``r`` starts driver ``(i + r) mod n`` in grid slot ``i``), so over ``n`` races
every driver starts from every slot once: nobody is helped by always starting at the
front. Points per finishing position follow Formula 1 (25, 18, 15, 12, 10, 8, 6, 4); cars
that do not finish score nothing.
"""

from __future__ import annotations

import csv
import json
from collections.abc import Callable
from pathlib import Path
from typing import Any

from neurodrive.experiments.metadata import run_metadata
from neurodrive.replay.lab import Entry
from neurodrive.replay.race import record_race

POINTS = (25, 18, 15, 12, 10, 8, 6, 4)


def run_grand_prix(
    entries: list[Entry],
    tracks: list[str],
    laps: int,
    out: Path,
    log: Callable[[str], None] = print,
) -> dict[str, Any]:
    n = len(entries)
    if not 2 <= n <= len(POINTS):
        raise ValueError(f"a Grand Prix needs 2 to {len(POINTS)} drivers")
    rows: list[dict[str, Any]] = []
    for r, track in enumerate(tracks):
        order = [(i + r) % n for i in range(n)]
        log(f"race {r + 1}/{len(tracks)}: {track}")
        reps = record_race(
            [entries[k] for k in order], track, laps=laps, log=log, with_network=False
        )
        for slot, (k, rep) in enumerate(zip(order, reps, strict=True)):
            race = rep.meta["race"]
            finished = race["outcome"] == "finished"
            rows.append(
                {
                    "race": r + 1,
                    "track": track,
                    "driver": entries[k][0],
                    "kind": rep.meta["kind_description"],
                    "grid": slot + 1,
                    "position": race["position"],
                    "outcome": race["outcome"],
                    "finish_time": rep.meta["finish_time"],
                    "contacts": race["contacts"],
                    "points": POINTS[race["position"] - 1] if finished else 0,
                }
            )
    out.mkdir(parents=True, exist_ok=True)
    with (out / "races.csv").open("w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    table = []
    for label, *_ in entries:
        mine = [row for row in rows if row["driver"] == label]
        outcomes: dict[str, int] = {}
        for row in mine:
            outcomes[row["outcome"]] = outcomes.get(row["outcome"], 0) + 1
        table.append(
            {
                "driver": label,
                "kind": mine[0]["kind"],
                "points": sum(row["points"] for row in mine),
                "wins": sum(1 for row in mine if row["position"] == 1 and row["points"]),
                "finished": outcomes.get("finished", 0),
                "races": len(mine),
                "mean_position": sum(row["position"] for row in mine) / len(mine),
                "contacts": sum(row["contacts"] for row in mine),
                "outcomes": outcomes,
            }
        )
    table.sort(key=lambda t: (-t["points"], t["mean_position"]))
    summary = {
        "tracks": tracks,
        "laps": laps,
        "drivers": [e[0] for e in entries],
        "models": {e[0]: e[3] or None for e in entries},
        "standings": table,
        "metadata": run_metadata(),
    }
    (out / "standings.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")
    lines = [
        f"# Grand Prix: {len(tracks)} races, {laps} laps each",
        "",
        "Generated by `neurodrive grand-prix`. Grid rotated every race; F1 points for "
        "finishers (25, 18, 15, 12, 10, 8, 6, 4).",
        "",
        "| # | Driver | Type | Points | Wins | Finished | Avg. position | Hits | Did not finish |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for place, t in enumerate(table, start=1):
        dnf = ", ".join(f"{k} {v}" for k, v in sorted(t["outcomes"].items()) if k != "finished")
        lines.append(
            f"| {place} | {t['driver']} | {t['kind']} | {t['points']} | {t['wins']} | "
            f"{t['finished']}/{t['races']} | {t['mean_position']:.1f} | {t['contacts']} | "
            f"{dnf or '-'} |"
        )
    lines += ["", "Tracks: " + ", ".join(f"`{t}`" for t in tracks)]
    (out / "standings.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    log("\n".join(lines))
    return summary
