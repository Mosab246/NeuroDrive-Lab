"""Export tracks, the car, and trained PPO/NEAT drivers for the browser version (``web/``).

The browser runs a JavaScript port of the kinematic simulator (``web/sim.js``). Everything
it needs is written to one ES module, ``web/data.js``, at full float precision so the port
can be checked step for step against the Python simulator (``tests/smoke/test_web_port.py``).

* PPO: the policy network's weights (11 -> 64 -> 64 -> 2, tanh). The browser computes the
  mean action, exactly what ``deterministic=True`` uses in Python.
* NEAT: the feed-forward evaluation list neat-python builds (node, bias, response, links),
  in evaluation order.
"""

from __future__ import annotations

import dataclasses
import json
from pathlib import Path
from typing import Any

from neurodrive.agents.model_io import load_controller, read_model_meta
from neurodrive.env.config import EnvConfig
from neurodrive.sim.simulation import SimConfig
from neurodrive.sim.track import Track, load_any_track
from neurodrive.sim.vehicle import VehicleParams

DEFAULT_TRACKS = (
    "beginner_oval",
    "curved_circuit",
    "technical_circuit",
    "validation_circuit",
    "unseen_a",
    "unseen_b",
    "proc_1",
    "proc_4",
    "proc_8",
    "proc_15",
)


def track_data(track: Track) -> dict[str, Any]:
    return {
        "id": track.id,
        "name": track.spec.name,
        "split": track.spec.split,
        "length": track.length,
        "centerline": track.centerline.tolist(),
        "cum_s": track.cum_s.tolist(),
        "tangents": track.tangents.tolist(),
        "normals": track.normals.tolist(),
        "curvature": track.curvature.tolist(),
        "half_width": track.half_width.tolist(),
        "left_edge": track.left_edge.tolist(),
        "right_edge": track.right_edge.tolist(),
        "checkpoint_s": track.checkpoint_s.tolist(),
        "window": track.index.window,
    }


def model_data(path: Path, label: str) -> dict[str, Any]:
    meta = read_model_meta(path)
    env = EnvConfig.model_validate(meta["env_config"])
    if env.physics.model != "kinematic" or env.observation.route_features:
        raise ValueError(f"{path}: the browser port supports the default kinematic setup only")
    return controller_data(load_controller(path), label) | {
        "observation": meta["observation"]["names"]
    }


def controller_data(controller: Any, label: str) -> dict[str, Any]:
    """The weights a browser needs to run a loaded PPO or NEAT controller."""
    base: dict[str, Any] = {"label": label, "kind": controller.kind}
    if controller.kind == "ppo":
        policy = controller.model.policy
        layers = [
            {"w": m.weight.detach().double().tolist(), "b": m.bias.detach().double().tolist()}
            for m in [*list(policy.mlp_extractor.policy_net), policy.action_net]
            if hasattr(m, "weight")
        ]
        return base | {"layers": layers, "activation": policy.activation_fn.__name__}
    net = controller.net
    evals = [
        {"node": node, "bias": bias, "response": response, "links": [[i, w] for i, w in links]}
        for node, _act, _agg, bias, response, links in net.node_evals
    ]
    return base | {"inputs": net.input_nodes, "outputs": net.output_nodes, "evals": evals}


def export_web(
    models: list[tuple[str, Path]],
    out: Path,
    tracks: tuple[str, ...] = DEFAULT_TRACKS,
    extra_models: list[dict[str, Any]] | None = None,
) -> Path:
    data = {
        "vehicle": dataclasses.asdict(VehicleParams()),
        "sim": {"dt": SimConfig().dt, "substeps": SimConfig().substeps},
        "sensors": EnvConfig().sensors.model_dump(mode="json"),
        "tracks": [track_data(load_any_track(t)) for t in tracks],
        "models": [model_data(path, label) for label, path in models] + (extra_models or []),
    }
    out.parent.mkdir(parents=True, exist_ok=True)
    body = json.dumps(data, separators=(",", ":"))
    out.write_text(
        "// Generated by `neurodrive export-web`; do not edit.\nexport const DATA = "
        + body
        + ";\n",
        encoding="utf-8",
    )
    return out
