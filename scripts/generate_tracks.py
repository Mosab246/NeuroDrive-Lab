"""Write the built-in Phase 5 track files from their shape formulas.

Run from the repository root:  uv run python scripts/generate_tracks.py

The YAML files it writes are committed; this script documents exactly how they were made.
The Beginner Oval is hand-written and not touched.
"""

from __future__ import annotations

from pathlib import Path

import yaml

from neurodrive.sim.procedural import RadialShape, shape_spec
from neurodrive.sim.track import build_track

OUT = Path("src/neurodrive/tracks")

DESIGNS = [
    # id, name, split, difficulty, width, shape
    (
        "curved_circuit",
        "Curved Circuit",
        "train",
        "medium",
        12.0,
        RadialShape(90.0, ((2, 0.18, 0.0), (3, 0.08, 0.5)), clockwise=True),
    ),
    (
        "technical_circuit",
        "Technical Circuit",
        "train",
        "hard",
        10.0,
        RadialShape(80.0, ((2, 0.08, 0.6), (3, 0.16, 0.3), (5, 0.05, 1.0))),
    ),
    (
        "validation_circuit",
        "Validation Circuit",
        "validation",
        "medium-hard",
        11.0,
        RadialShape(85.0, ((2, 0.16, 1.0), (4, 0.07, 0.0))),
    ),
    (
        "unseen_a",
        "Unseen Circuit A",
        "test",
        "medium-hard",
        11.0,
        RadialShape(85.0, ((2, 0.08, 0.2), (3, 0.17, 1.2)), clockwise=True),
    ),
    (
        "unseen_b",
        "Unseen Circuit B",
        "test",
        "hard",
        10.0,
        RadialShape(80.0, ((1, 0.12, 0.0), (4, 0.10, 0.7), (2, 0.08, 2.0))),
    ),
]


def main() -> None:
    for track_id, name, split, difficulty, width, shape in DESIGNS:
        spec = shape_spec(track_id, name, shape, width=width, split=split, difficulty=difficulty)
        track = build_track(spec)  # raises if invalid
        direction = "clockwise" if shape.clockwise else "counter-clockwise"
        header = (
            f"# {name}: generated by scripts/generate_tracks.py, do not edit by hand.\n"
            f"# Radial shape: radius {shape.radius:g} m, terms (k, amplitude, phase) "
            f"{list(shape.terms)}, driven {direction}.\n"
            f"# Length {track.length:.1f} m, tightest turn radius "
            f"{1 / abs(track.curvature).max():.1f} m.\n"
        )
        body = yaml.safe_dump(spec.model_dump(mode="json"), sort_keys=False)
        body = body.replace("control_points:\n", "control_points:\n", 1)
        (OUT / f"{track_id}.yaml").write_text(header + body, encoding="utf-8")
        print(
            f"{track_id:<20} {split:<10} {direction:<18} length {track.length:6.1f} m  "
            f"width {width:4.1f} m  tightest radius {1 / abs(track.curvature).max():5.1f} m"
        )


if __name__ == "__main__":
    main()
